#!/usr/bin/env python3
"""Generate the committed trigonometry tables of palimpsest_math.

SPEC: canon §1.9 (sine table T), doc 02 §4.3 (SIN_T layout and integrity hash)
and doc 02 §4.4 (CORDIC arctangent table ATAN_T).

Outputs (paths relative to the workspace root, the parent of tools/):

  crates/palimpsest_math/src/trig_table.rs   pub static SIN_T: [i32; 16385]
  crates/palimpsest_math/src/cordic_table.rs pub const ATAN_T: [i64; 16]

Definitions:

  SIN_T[i]  = round_half_even(sin(2*pi*i/65536) * 2^30), i in 0..=16384  (Q2.30)
  ATAN_T[i] = round_half_even(atan(2^-i) / (2*pi) * 2^32), i in 0..=15  (2^-16 Bam units)

Both are evaluated with mpmath at 50 significant decimal digits. Rounding is
done by an exact rational decision on the mpmath value: the script refuses to
emit any entry whose fractional part lies within 10^-30 of one half (an
ambiguous tie), so a tie can only be resolved when the value is exactly an
integer (i = 0 and i = 16384, which are computed exactly).

The script is deterministic and re-runnable. Usage:

  python3 tools/gen_trig.py           regenerate both files in place
  python3 tools/gen_trig.py --check   exit 1 if a committed file differs

The generated files carry no timestamp or tool version, so regenerating on any
machine with any mpmath release that evaluates these functions correctly to 50
digits yields byte-identical output. The Rust tests in trig.rs re-verify length,
endpoints, monotonicity, spot values and the doc 02 §4.3 BLAKE3 integrity hash.
"""

import argparse
import os
import sys

import mpmath

DIGITS = 50
TABLE_LEN = 16385
QUARTER = 16384
ONE_Q30 = 1 << 30
ATAN_LEN = 16
PER_LINE_SIN = 8
PER_LINE_ATAN = 4

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "crates", "palimpsest_math", "src")
SIN_PATH = os.path.join(SRC, "trig_table.rs")
ATAN_PATH = os.path.join(SRC, "cordic_table.rs")


def round_half_even(v):
    """Round an mpmath real to the nearest integer, ties to even.

    Refuses values that are not exact integers but lie within 1e-30 of a
    half-integer, because 50 digits cannot decide them.
    """
    fl = int(mpmath.floor(v))
    frac = v - fl
    half = mpmath.mpf(1) / 2
    eps = mpmath.mpf(10) ** -30
    if frac != half and abs(frac - half) < eps:
        raise SystemExit("ambiguous tie at value %s" % mpmath.nstr(v, 40))
    if frac > half:
        return fl + 1
    if frac < half:
        return fl
    return fl + (fl & 1)


def sin_table():
    out = []
    for i in range(TABLE_LEN):
        if i == 0:
            out.append(0)
            continue
        if i == QUARTER:
            out.append(ONE_Q30)
            continue
        v = mpmath.sin(2 * mpmath.pi * i / 65536) * ONE_Q30
        out.append(round_half_even(v))
    return out


def atan_table():
    out = []
    for i in range(ATAN_LEN):
        if i == 0:
            # atan(1) / (2 pi) = 1/8 exactly, so the entry is exactly 2^29.
            out.append(1 << 29)
            continue
        v = mpmath.atan(mpmath.mpf(2) ** -i) / (2 * mpmath.pi) * (mpmath.mpf(2) ** 32)
        out.append(round_half_even(v))
    return out


def check_sin(t):
    assert len(t) == TABLE_LEN
    assert t[0] == 0 and t[QUARTER] == ONE_Q30
    for i in range(1, TABLE_LEN):
        assert t[i] > t[i - 1], "table not strictly increasing at %d" % i
    # Spot values from doc 02 §4.3.
    spots = {1: 102944, 2: 205887, 4096: 410903207, 8192: 759250125,
             10923: 929904853, 16383: 1073741819, 16384: 1073741824}
    for k, v in spots.items():
        assert t[k] == v, "spot value T[%d] = %d, doc 02 says %d" % (k, t[k], v)


def check_atan(a):
    expected = [536870912, 316933406, 167458907, 85004756, 42667331, 21354465,
                10679838, 5340245, 2670163, 1335087, 667544, 333772, 166886,
                83443, 41722, 20861]
    assert a == expected, "ATAN_T differs from doc 02 §4.4: %r" % (a,)


HEADER = """// @generated by tools/gen_trig.py (mpmath, {digits} digits). Do not edit by hand.
// Regenerate with `python3 tools/gen_trig.py`; verify with `python3 tools/gen_trig.py --check`.
"""


def render_sin(t):
    lines = [HEADER.format(digits=DIGITS)]
    lines.append("//! SPEC: canon §1.9 sine table T, doc 02 §4.3.\n")
    lines.append("\n")
    lines.append("/// SPEC: canon §1.9. `SIN_T[i] = round_half_even(sin(2*pi*i/65536) * 2^30)`\n")
    lines.append("/// for `i` in `0..=16384`, in Q2.30. `SIN_T[16384] = 1073741824`.\n")
    lines.append("#[rustfmt::skip]\n")
    lines.append("pub static SIN_T: [i32; 16385] = [\n")
    for start in range(0, TABLE_LEN, PER_LINE_SIN):
        chunk = t[start:start + PER_LINE_SIN]
        lines.append("    " + ", ".join(str(v) for v in chunk) + ",\n")
    lines.append("];\n")
    return "".join(lines)


def render_atan(a):
    lines = [HEADER.format(digits=DIGITS)]
    lines.append("//! SPEC: doc 02 §4.4 CORDIC arctangent table.\n")
    lines.append("\n")
    lines.append("/// SPEC: canon §1.9, doc 02 §4.4. `ATAN_T[i] = round_half_even(atan(2^-i) / (2*pi) * 2^32)`\n")
    lines.append("/// for `i` in `0..=15`, in units of 2^-16 Bam (one full turn is 2^32).\n")
    lines.append("#[rustfmt::skip]\n")
    lines.append("pub const ATAN_T: [i64; 16] = [\n")
    for start in range(0, ATAN_LEN, PER_LINE_ATAN):
        chunk = a[start:start + PER_LINE_ATAN]
        lines.append("    " + ", ".join(str(v) for v in chunk) + ",\n")
    lines.append("];\n")
    return "".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="compare against the committed files instead of writing")
    args = ap.parse_args()

    mpmath.mp.dps = DIGITS
    t = sin_table()
    a = atan_table()
    check_sin(t)
    check_atan(a)
    outputs = [(SIN_PATH, render_sin(t)), (ATAN_PATH, render_atan(a))]

    if args.check:
        ok = True
        for path, text in outputs:
            try:
                with open(path, "r", encoding="utf-8", newline="") as f:
                    cur = f.read()
            except FileNotFoundError:
                cur = None
            if cur != text:
                print("DIFFERS: %s" % os.path.relpath(path, ROOT))
                ok = False
            else:
                print("ok: %s" % os.path.relpath(path, ROOT))
        sys.exit(0 if ok else 1)

    for path, text in outputs:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote %s" % os.path.relpath(path, ROOT))


if __name__ == "__main__":
    main()
