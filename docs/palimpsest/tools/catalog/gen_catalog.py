"""Generate spec/20_CONTENT_CATALOG.md from the validated content store.

Reads palimpsest/content/**/*.json (records and namespace metadata) and writes
the catalog. Only records present on disk appear; the catalog says so.
Usage: python gen_catalog.py            (writes the chapter)
       python gen_catalog.py --check    (exit 1 if the chapter is stale)
"""
import json, sys, pathlib, collections
HERE = pathlib.Path(__file__).resolve().parent
DOCS = HERE.parents[1]
CONTENT = DOCS.parents[1] / "palimpsest" / "content"
OUT = DOCS / "spec" / "20_CONTENT_CATALOG.md"

def load_records():
    recs, files = [], []
    for p in sorted(CONTENT.rglob("*.json")):
        d = json.loads(p.read_text(encoding="utf-8"))
        rows = d.get("records", []) if isinstance(d, dict) else d
        files.append((p.relative_to(CONTENT).as_posix(), len(rows)))
        recs.extend((p.relative_to(CONTENT).as_posix(), r) for r in rows)
    return recs, files

def render():
    recs, files = load_records()
    ns = [r for _, r in recs if r.get("kind") == "prefix"]
    retired = [r for _, r in recs if r.get("kind") == "retired"]
    game = [(f, r) for f, r in recs if r.get("kind") not in ("prefix", "retired")]
    by_owner = collections.defaultdict(list)
    for r in ns:
        by_owner[r.get("owner_text", "")].append(r)
    L = []
    L.append("# 20 Content catalog")
    L.append("")
    L.append("As of 2026-10-12. Status: PARTIAL. Generated by `tools/catalog/gen_catalog.py` from `palimpsest/content/`. Do not hand-edit.")
    L.append("")
    L.append("## Imports")
    L.append("")
    L.append("| Source | Section | What this chapter consumes |")
    L.append("|---|---|---|")
    L.append("| Canon | §19 | Namespace ownership, one row per prefix |")
    L.append("| Canon | §17.7 | Retired IDs |")
    L.append("| Doc 19 | §1 to §7 | Content file layout, envelope and record schemas |")
    L.append("| DECISIONS.md | 128, 132, 137 | Seeds, Prologue and first-run achievement retirements |")
    L.append("")
    L.append("## 1. Coverage")
    L.append("")
    L.append(f"Namespace prefixes on disk: {len(ns)}. Retired IDs on disk: {len(retired)}. Game records on disk: {len(game)} across {len(files)} files.")
    L.append("")
    L.append("Game records are not yet extracted. The per-chapter tables that describe them (about 5,800 IDs in the Exports sections) must be written into `palimpsest/content/<owner>/<namespace>/*.json` before this catalog lists them. Until then this chapter lists only the namespace layer.")
    L.append("")
    L.append("## 2. Namespaces by owner")
    L.append("")
    L.append("| Owner chapter | Prefixes | Prefix list |")
    L.append("|---|---|---|")
    for owner in sorted(by_owner):
        pref = sorted(r["prefix"] for r in by_owner[owner])
        L.append(f"| {owner or 'none'} | {len(pref)} | {', '.join('`'+p+'`' for p in pref)} |")
    L.append("")
    L.append("## 3. Retired IDs")
    L.append("")
    L.append("| ID | Source |")
    L.append("|---|---|")
    for r in sorted(retired, key=lambda r: r["retired"]):
        L.append(f"| {r['retired']} | {r.get('source', '')} |")
    L.append("")
    L.append("## 4. Game records")
    L.append("")
    if game:
        L.append("| ID | Kind | File |")
        L.append("|---|---|---|")
        for f, r in sorted(game, key=lambda x: x[1].get("id", "")):
            L.append(f"| `{r.get('id','')}` | {r.get('kind','')} | {f} |")
    else:
        L.append("None on disk.")
    L.append("")
    L.append("## Exports")
    L.append("")
    L.append("None. This chapter defines no IDs.")
    L.append("")
    L.append("## Interface assumptions")
    L.append("")
    L.append("| Chapter | Assumption | Present |")
    L.append("|---|---|---|")
    L.append("| 19 | Record files and envelope match the schemas in §5 | assumed |")
    L.append("| 00 | `meta.` namespace records match canon §19 | present (gen_namespaces --check) |")
    L.append("")
    L.append("## Canon gaps")
    L.append("")
    L.append("- The catalog needs one extraction pass per owner chapter. Canon does not define that pass, so its scope is a product decision: extract all about 5,800 IDs, or extract only the records a first milestone needs.")
    L.append("")
    L.append("## Acceptance tests")
    L.append("")
    L.append("1. Running `gen_catalog.py --check` after a fresh generation exits 0.")
    L.append("2. No retired ID from §3 appears as a game record in section 4.")
    L.append("3. The section 1 counts equal the counts computed from `palimpsest/content/`.")
    L.append("")
    L.append("## Invariants annex")
    L.append("")
    L.append("W! this chapter is regenerated from `palimpsest/content/`, never hand-edited.")
    L.append("N! a retired ID appears in section 4.")
    L.append("")
    return "\n".join(L)

if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        print("catalog matches" if cur == text else "catalog is stale")
        sys.exit(0 if cur == text else 1)
    OUT.write_text(text, encoding="utf-8")
    print("wrote", OUT)
