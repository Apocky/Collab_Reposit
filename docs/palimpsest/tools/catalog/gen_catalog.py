"""Generate spec/20_CONTENT_CATALOG.md from the validated content store.

Reads palimpsest/content/**/*.json (namespace records and extracted table records,
written by extract_content.py) and audit/catalog_unowned.txt (canon gaps).
Usage: python gen_catalog.py            (writes the chapter)
       python gen_catalog.py --check    (exit 1 if the chapter is stale)
"""
import json
import sys
import pathlib
import collections

HERE = pathlib.Path(__file__).resolve().parent
DOCS = HERE.parents[1]
CONTENT = DOCS.parents[1] / "palimpsest" / "content"
OUT = DOCS / "spec" / "20_CONTENT_CATALOG.md"
UNOWNED = DOCS / "audit" / "catalog_unowned.txt"


def load_records():
    recs, files = [], []
    for p in sorted(CONTENT.rglob("*.json")):
        d = json.loads(p.read_text(encoding="utf-8"))
        rows = d.get("records", []) if isinstance(d, dict) else d
        files.append((p.relative_to(CONTENT).as_posix(), len(rows)))
        recs.extend(rows)
    return recs, files


def render():
    recs, files = load_records()
    ns = [r for r in recs if r.get("kind") == "prefix"]
    retired = [r for r in recs if r.get("kind") == "retired"]
    game = [r for r in recs if r.get("kind") not in ("prefix", "retired")]
    unowned = []
    if UNOWNED.exists():
        unowned = [ln.split("\t")[0] for ln in UNOWNED.read_text(encoding="utf-8").splitlines() if ln.strip()]
    per_owner = collections.Counter(r["owner"] for r in game)
    per_kind = collections.Counter(r["kind"] for r in game)
    L = []
    L.append("# 20 Content catalog")
    L.append("")
    L.append("As of 2026-10-12. Status: EXTRACTED. Generated by `tools/catalog/gen_catalog.py` from `palimpsest/content/`, which `tools/catalog/extract_content.py` fills from the chapter tables. Do not hand-edit.")
    L.append("")
    L.append("## Imports")
    L.append("")
    L.append("| Source | Section | What this chapter consumes |")
    L.append("|---|---|---|")
    L.append("| Canon | §19 | Namespace ownership (generated into `meta.` records) |")
    L.append("| Canon | §17.7 | Retired IDs |")
    L.append("| Doc 19 | §1 to §7 | Content file layout, envelope and record schema pattern |")
    L.append("| Chapters 00 to 18 | Every table whose first cell is a backticked ID | The record source |")
    L.append("")
    L.append("## 1. Coverage")
    L.append("")
    L.append(f"Game records: {len(game)} from {len(per_owner)} owner chapters. Namespace prefixes: {len(ns)}. Retired IDs: {len(retired)}. Content files: {len(files)}.")
    L.append("")
    L.append("Each record keeps its table row as text in `fields`. Field values are not checked against per-kind schemas yet; the schema per owner only checks the envelope and the owner.")
    L.append("")
    L.append("## 2. Records by owner chapter")
    L.append("")
    L.append("| Owner | Records |")
    L.append("|---|---|")
    for o in sorted(per_owner):
        L.append(f"| {o} | {per_owner[o]} |")
    L.append("")
    L.append("## 3. Records by namespace")
    L.append("")
    L.append("| Namespace | Records |")
    L.append("|---|---|")
    for k in sorted(per_kind):
        L.append(f"| {k} | {per_kind[k]} |")
    L.append("")
    L.append("## 4. Namespaces without a canon owner")
    L.append("")
    if unowned:
        L.append("These IDs use namespaces that canon §19 does not define. They are not written to the store. Canon must add the namespaces or the IDs must move.")
        L.append("")
        L.append("| # | ID | Chapter |")
        L.append("|---|---|---|")
        for n, ln in enumerate(sorted(UNOWNED.read_text(encoding="utf-8").splitlines()), 1):
            if ln.strip():
                cid, _, ch = ln.partition("\t")
                L.append(f"| {n} | `{cid}` | {ch} |")
    else:
        L.append("None.")
    L.append("")
    L.append("## 5. Retired IDs")
    L.append("")
    L.append("| ID | Source |")
    L.append("|---|---|")
    for r in sorted(retired, key=lambda r: r["retired"]):
        L.append(f"| {r['retired']} | {r.get('source', '')} |")
    L.append("")
    L.append("## 6. Game records")
    L.append("")
    L.append("| # | ID | Namespace | Owner | Section | Also in |")
    L.append("|---|---|---|---|---|---|")
    for n, r in enumerate(sorted(game, key=lambda x: x["id"]), 1):
        also = "; ".join(r.get("also_in", [])) or "none"
        L.append(f"| {n} | `{r['id']}` | {r['kind']} | {r['owner']} | {r.get('section', '')} | {also} |")
    L.append("")
    L.append("## Exports")
    L.append("")
    L.append("None. This chapter defines no IDs.")
    L.append("")
    L.append("## Interface assumptions")
    L.append("")
    L.append("| Chapter | Assumption | Present |")
    L.append("|---|---|---|")
    L.append("| 19 | Record files and envelope match the schemas written by extract_content.py | present (validate_content: 0 errors) |")
    L.append("| 00 | `meta.` namespace records match canon §19 | present (gen_namespaces --check) |")
    L.append("| 00 to 18 | Each table row keeps its ID in the first cell | present (extracted rows) |")
    L.append("")
    L.append("## Canon gaps")
    L.append("")
    L.append("- Namespaces in section 4 have no canon owner. Canon §19 must add them.")
    L.append("- Per-kind field schemas are not written. Each owner chapter must define its kinds before field values are validated.")
    L.append("")
    L.append("## Acceptance tests")
    L.append("")
    L.append("1. `validate_content.py` reports 0 errors after extract_content.py runs.")
    L.append("2. No retired ID from section 5 appears as a game record in section 6.")
    L.append("3. The section 1 counts equal the counts computed from `palimpsest/content/`.")
    L.append("")
    L.append("## Invariants annex")
    L.append("")
    L.append("W! this chapter is regenerated from `palimpsest/content/`, never hand-edited.")
    L.append("N! a record appears in section 6 without an owner chapter.")
    L.append("")
    return "\n".join(L)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        print("catalog matches" if cur == text else "catalog is stale")
        sys.exit(0 if cur == text else 1)
    OUT.write_text(text, encoding="utf-8")
    print("wrote", OUT)
