"""Extract every backticked-ID table row from spec chapters into palimpsest content.

One record per distinct ID. Owner: the chapter where the ID appears, when canon 19
assigns the namespace to that chapter; otherwise the first canon owner. IDs whose
namespace canon 19 does not define are not written; they are listed in
audit/catalog_unowned.txt as canon gaps.

Writes:
  palimpsest/content/<owner>/<namespace>/records.json   (schema <owner>.table_row)
  palimpsest/schemas/<owner>.table_row.schema.json
Usage: python extract_content.py
"""
import json
import re
import sys
import pathlib
import collections

HERE = pathlib.Path(__file__).resolve().parent
DOCS = HERE.parents[1]


SPEC = DOCS / "spec"
PAL = DOCS.parents[1] / "palimpsest"
ID = re.compile(r"^[a-z][a-z0-9_]*(\.[a-z0-9_]+){1,5}$")

NS = json.loads((PAL / "content" / "00" / "meta" / "namespaces.json").read_text(encoding="utf-8"))["records"]
PREFIX_OWNERS = {r["prefix"]: r["owners"] for r in NS if r.get("kind") == "prefix"}


def owners_for(cid):
    """Record owners of the longest canon prefix that matches cid (generated namespace table)."""
    best = None
    for pf in PREFIX_OWNERS:
        if cid.startswith(pf) and (best is None or len(pf) > len(best)):
            best = pf
    return (best, PREFIX_OWNERS.get(best, []))


def table_rows(text):
    """Yield (section_title, header_cells, row_cells) for every data row of every table."""
    section = ""
    header = None
    for line in text.split("\n"):
        if re.match(r"^#{2,4}\s", line):
            section = line.lstrip("#").strip()
            header = None
            continue
        if not line.startswith("|"):
            header = None
            continue
        if line.startswith("|---") or line.startswith("| ---"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if header is None:
            header = cells
            continue
        yield section, header, cells


rows = collections.OrderedDict()
for f in sorted(SPEC.glob("[0-1][0-9]_*.md")):
    n = f.name[:2]
    for section, header, cells in table_rows(f.read_text(encoding="utf-8")):
        m = re.fullmatch(r"`([^`]+)`", cells[0]) if cells else None
        if not (m and ID.match(m.group(1))):
            continue
        cid = m.group(1)
        if cid in rows:
            rows[cid]["also_in"].append(f"{n} {section}")
            continue
        fields = {}
        for k, v in zip(header[1:], cells[1:]):
            key = re.sub(r"[^a-z0-9]+", "_", k.lower()).strip("_") or "col"
            if key in fields:
                key += "_2"
            fields[key] = v
        rows[cid] = {"id": cid, "kind": cid.split(".")[0], "owner": None,
                     "section": f"{n} {section}", "fields": fields,
                     "also_in": [], "_chapter": n}

by_file = collections.defaultdict(list)
unowned = []
for cid, r in list(rows.items()):
    pf, owners = owners_for(cid)
    if pf is None:
        unowned.append((cid, r.pop("_chapter")))
        del rows[cid]
        continue
    chap = r.pop("_chapter")
    owner = chap if chap in owners else owners[0]
    r["owner"] = owner
    by_file[(owner, cid.split(".")[0])].append(r)

for p in (PAL / "content").rglob("records.json"):
    p.unlink()

owners_used = set()
for (owner, ns), recs in sorted(by_file.items()):
    d = PAL / "content" / owner / ns
    d.mkdir(parents=True, exist_ok=True)
    body = {"schema": f"{owner}.table_row", "records": recs}
    (d / "records.json").write_text(json.dumps(body, ensure_ascii=False, indent=1), encoding="utf-8")
    owners_used.add(owner)

for owner in sorted(owners_used):
    schema = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": f"urn:palimpsest:schema:{owner}.table_row",
        "title": f"Table row records of chapter {owner}",
        "description": "Generated by tools/catalog/extract_content.py from a chapter table row whose first cell is a backticked ID. Fields keep the table text; field semantics are not validated.",
        "x-owner": owner,
        "$ref": "urn:palimpsest:schema:common#/$defs/record_base",
        "unevaluatedProperties": False,
        "required": ["kind", "owner", "section", "fields"],
        "properties": {
            "kind": {"type": "string", "minLength": 1},
            "owner": {"type": "string", "pattern": "^(0[0-9]|1[0-8]|21)$"},
            "section": {"type": "string"},
            "fields": {"type": "object", "additionalProperties": {"type": "string"}},
            "also_in": {"type": "array", "items": {"type": "string"}},
        },
    }
    (PAL / "schemas" / f"{owner}.table_row.schema.json").write_text(
        json.dumps(schema, ensure_ascii=False, indent=1), encoding="utf-8")

lines = [f"{cid}\tchapter {ch}" for cid, ch in unowned]
(DOCS / "audit" / "catalog_unowned.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("unowned (namespace not in canon 19):", len(unowned))
print("records:", len(rows), "files:", len(by_file), "owners:", sorted(owners_used))
